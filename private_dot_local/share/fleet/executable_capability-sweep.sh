#!/bin/bash
# fleet-capability-sweep — weekly scan of the external skills/MCP ecosystem
# for capabilities the estate lacks, deduped against what's installed.
#
# Output: ~/.local/share/fleet/discovery/YYYY-MM-DD.md
# The estate-first AGENTS.md rule points sessions at the latest report.
#
# Sources: skills.sh (agent skills), GitHub (skills + MCP servers),
# awesome-mcp-servers, smithery.ai. Dedupe: installed skills + estate MCP
# servers + repos under ~/dev/src/github.com/WyattAu.
#
# Topics track the estate's actual work domains — edit TOPICS to retarget.

set -u

OUT_DIR="$HOME/.local/share/fleet/discovery"
mkdir -p "$OUT_DIR"
TODAY="$(date +%F)"
OUT="$OUT_DIR/$TODAY.md"
LATEST="$OUT_DIR/latest.md"
LOCK="/tmp/fleet-capability-sweep.lock"

# One sweep at a time (timer + manual overlap).
exec 9>"$LOCK"
flock -n 9 || exit 0

TOPICS=(
  "rust code search"
  "browser automation agent"
  "security scanner agent"
  "fleet orchestration"
  "llm evaluation"
  "mcp server security"
  "terminal coding agent"
)

# --- inventory what's installed (dedupe baseline) --------------------------
INSTALLED_SKILLS="$(ls ~/.agents/skills 2>/dev/null | sort -u | tr '\n' ',' )"
ESTATE_MCPS="$(grep -rhoE '"[a-z0-9_-]+"' ~/.config/opencode/mcp_servers.json 2>/dev/null | tr '\n' ',' )"
[ -f "$OUT" ] && exit 0  # one report per day

{
  echo "# Fleet capability sweep — $TODAY"
  echo
  echo "Generated by fleet-capability-sweep (systemd timer). Deduped against"
  echo "installed skills + estate MCP servers + WyattAu repos at scan time."
  echo
  echo "## Installed baseline"
  echo
  echo "- Skills: $(ls ~/.agents/skills 2>/dev/null | wc -l) in ~/.agents/skills"
  echo "- Estate repos: $(ls ~/dev/src/github.com/WyattAu 2>/dev/null | wc -l) in ~/dev/src/github.com/WyattAu"
  echo
  echo "## Findings by topic"
  echo

  for topic in "${TOPICS[@]}"; do
    echo "### $topic"
    echo
    slug="$(echo "$topic" | tr ' ' '-')"

    # skills.sh — top matches for this topic
    echo "#### skills.sh"
    echo
    if command -v bunx >/dev/null 2>&1; then
      results="$(cd /tmp && timeout 90 bunx skills find "$topic" 2>/dev/null \
        | grep -oE '[a-zA-Z0-9_-]+/[a-zA-Z0-9._-]+@[a-zA-Z0-9._-]+ [0-9,]+ installs' \
        | head -6)"
      if [ -n "$results" ]; then
        echo '```'
        echo "$results"
        echo '```'
      else
        echo "(no results or timeout)"
      fi
    fi
    echo

    # GitHub — repos matching the topic, stars ≥ 20, pushed this year
    echo "#### GitHub"
    echo
    results="$(gh search repos "$topic" --sort stars --limit 5 \
      --json fullName,stargazersCount,description 2>/dev/null \
      | jq -r '.[] | select(.stargazersCount >= 20) | "\(.stargazersCount)* \(.fullName) — \(.description[0:100])"' \
      | head -5)"
    if [ -n "$results" ]; then
      echo '```'
      echo "$results"
      echo '```'
    else
      echo "(no results ≥20★)"
    fi
    echo
  done

  echo "## Estate MCP fleet (live)"
  echo
  echo "- aileron-agent :9543 (browser automation, 49 tools) — systemd"
  echo "- osint-kit — estate repo"
  echo "- memory / github / osint / standards — opencode MCP"
  echo
  echo "## Review workflow"
  echo
  echo "1. Skim the findings; anything interesting → symlink into"
  echo "   ~/.agents/skills/ (ECC/penthera pattern: clone to"
  echo "   ~/.local/share/<name>-skills, symlink the skill dir)."
  echo "2. Security-adjacent skills get the penthera-style audit first"
  echo "   (license, telemetry, exec patterns, authorization gates)."
  echo "3. MCP servers get a supply-chain review before install"
  echo "   (see ECC mcp-dependency-review)."
} > "$OUT"

ln -sfn "$OUT" "$LATEST"
echo "fleet-capability-sweep: wrote $OUT ($(wc -l < "$OUT") lines)"
